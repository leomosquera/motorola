            <p>Cuando el seguro rija de doce a doce horas, la rescisión se computará desde la hora doce inmediata siguiente, y en caso contrario, desde la hora veinticuatro. </p>

            <p>Si el Asegurador ejerce el derecho de rescindir, la prima se reducirá proporcionalmente por el plazo no corrido.</p>

            <p>Si el Asegurado opta por la rescisión, el Asegurador tendrá derecho a la prima devengada por el tiempo transcurrido, según las tarifas de corto plazo (Art. 18, segundo párrafo  - L. de S.).</p> 


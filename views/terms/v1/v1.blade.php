            <h2>ARTÍCULO 6</h2>

            <p>Quien asegura el mismo interés y el mismo riesgo con más de un asegurador, notificará sin dilación a cada uno de ellos los demás contratos celebrados con indicación del Asegurador y de la suma asegurada, bajo pena de caducidad. Con esta salvedad, en caso de siniestro el Asegurador contribuirá proporcionalmente al monto de su contrato, hasta la concurrencia de la indemnización debida.</p>

            <p>El Asegurado no puede pretender en el conjunto una indemnización que supere el monto del daño sufrido. Si se celebró el seguro plural con la intención de un enriquecimiento indebido, son nulos los contratos celebrados con esa intención, sin perjuicio del derecho de los aseguradores a percibir la prima devengada en el período durante el cual conocieron esa intención (Arts. 67 y 68 - L. de S.).</p>

            <h2 class="mt-4">PAGO DE LA PRIMA</h2>
            <h2>ARTÍCULO 7</h2>

            <p>La prima es debida desde la celebración del contrato pero no es exigible sino contra entrega de la Póliza, salvo que se haya emitido un certificado o instrumento provisorio de cobertura (Art. 30 - L. de S.).</p>

            <p>En el caso que la prima no se pague contra la entrega de la presente Póliza, su pago queda sujeto a las condiciones y efectos establecidos en la Cláusula de Cobranza del Premio que forma parte del presente contrato.</p>

            <h2 class="mt-4">PROVOCACIÓN DEL SINIESTRO</h2>
            <h2>ARTÍCULO 8</h2>

            <p>El Asegurador queda liberado si el Asegurado provoca por acción u omisión el siniestro, dolosamente o con culpa grave, salvo los actos realizados para precaver el siniestro o atenuar sus consecuencias o por un deber de humanidad generalmente aceptado (Arts. 70 - L. de S.). </p>

            <h2 class="mt-4">ABANDONO</h2>
            <h2>ARTÍCULO 9</h2>

            <p>El Asegurado no puede hacer abandono de los bienes afectados por el siniestro (Art. 74 - L de S.).</p>

            <h2 class="mt-4">CAMBIO EN LAS COSAS DAÑADAS</h2>
            <h2>ARTÍCULO 10</h2>

            <p>El Asegurado no puede, sin el consentimiento del Asegurador, introducir cambios en las cosas dañadas que hagan más difícil establecer la causa del daño o el daño mismo, salvo que se cumpla para disminuir el daño o en el interés público.</p>

            <p>El Asegurador sólo puede invocar esta disposición cuando proceda sin demoras a la determinación de las causas del siniestro y a la valuación de los daños.</p>

            <p>La violación maliciosa de esta carga libera al Asegurador (Art. 77 - L. de S.).</p>


            <h2 class="mt-4">DENUNCIA DEL SINIESTRO</h2>
            <h2>ARTÍCULO 11</h2>

            <p>El Asegurado está obligado a comunicar sin demora a las autoridades competentes el acaecimiento del hecho, cuando así corresponda por su naturaleza.</p>

            <p>El Asegurado debe denunciar al Asegurador el acaecimiento del siniestro dentro de los tres días de conocerlo, bajo pena de perder el derecho a ser indemnizado, salvo que acredite caso fortuito, fuerza mayor o imposibilidad de hecho sin culpa o negligencia (Arts. 46 y 47 - L. de S.).</p>

            <p>También está obligado a suministrar al Asegurador, a su pedido, la información necesaria para verificar el siniestro o la extensión de la prestación a su cargo, la prueba instrumental en cuanto sea razonable que la suministre y a permitirle al Asegurador las indagaciones necesarias a tales fines (Art. 46 - L. de S.).</p>


            <h2 class="mt-4">EXAGERACIÓN FRAUDULENTA O PRUEBA FALSA DEL SINIESTRO</h2>
            <h2>ARTÍCULO 12</h2>

            <p>El Asegurado pierde el derecho a ser indemnizado si deja de cumplir maliciosamente las cargas previstas en el segundo párrafo del Artículo 46 de la Ley de Seguros o exagera fraudulentamente los daños o emplea pruebas falsas para acreditar los mismos (Art. 48 - L. de S.).</p>

            <h2 class="mt-4">PLAZO PARA PRONUNCIARSE SOBRE EL DERECHO DEL ASEGURADO</h2>
            <h2>ARTÍCULO 13</h2>

            <p>El Asegurador debe pronunciarse acerca del derecho del Asegurado dentro de los treinta días de recibida la información complementaria que se requiera para la verificación del siniestro o de la extensión de la prestación a su cargo. La omisión de pronunciarse importa aceptación (Art. 56 - L. de S.).</p>


            <h2 class="mt-4">VENCIMIENTO DE LA OBLIGACIÓN DEL ASEGURADOR</h2>
            <h2>ARTÍCULO 14</h2>

            <p>En el caso de reparación o reemplazo, la Aseguradora cumplirá con la prestación a su cargo dentro de los 15 (quince) días de aceptada la procedencia del siniestro.</p>

            <p>En caso que la Aseguradora tuviera que dar en pago al Asegurado una suma de dinero en concepto de indemnización, el crédito del Asegurado se pagará dentro de los quince días de fijado el monto de la indemnización o de la aceptación de la indemnización ofrecida, una vez vencido el plazo fijado en la Cláusula precedente para que el Asegurador se pronuncie acerca del derecho del Asegurado.</p>


            <h2 class="mt-4">RESCISIÓN UNILATERAL</h2>
            <h2>ARTÍCULO 15</h2>

            <p>El Asegurado y el Asegurador tendrán derecho a rescindir la Póliza sin expresar causa. </p>


            <h2 class="mt-4">CARGA ESPECIAL</h2>
            <h2>ARTÍCULO 9</h2>

            <p>En caso de siniestro, el Asegurado deberá presentar el Equipo Asegurado, las piezas o partes reemplazadas, quedando éstas en propiedad del Asegurador.</p>

            <p>El incumplimiento por parte del Asegurado de esta carga especial hará perder al Asegurado el derecho a la indemnización de acuerdo al régimen del Artículo 36 de la Ley de Seguros.</p>

            <h2 class="mt-4">DENUNCIA DEL SINIESTRO</h2>
            <h2>ARTÍCULO 10</h2>

            <p>En concordancia con lo establecido en el Artículo 13 de las Condiciones Generales, el Asegurado deberá denunciar la ocurrencia del siniestro en los plazos allí establecidos.</p>

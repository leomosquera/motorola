            <h2 class="mt-4">AGRAVACIÓN DEL RIESGO</h2>
            <h2>ARTÍCULO 5</h2>

            <p>El Asegurado debe denunciar al Asegurador las agravaciones del riesgo asumido causadas por un hecho suyo, antes de que se produzcan y las debidas a un hecho ajeno, inmediatamente después de conocerlas (Art. 38 - L. de S.).</p>

            <p>Se entiende por agravación del riesgo asumido, la que si hubiese existido al tiempo de la celebración, a juicio de peritos, habría impedido este contrato o modificado sus condiciones (Art. 37 - L. de S.). </p>

            <p>Cuando la agravación se deba a un hecho del Asegurado la cobertura queda suspendida. El Asegurador, en el término de siete días, deberá notificar su decisión de rescindir (Art. 39 - L. de S.).</p>

            <p>Cuando la agravación resulte de un hecho ajeno al Asegurado o si éste debió permitirlo o provocarlo por razones ajenas a su voluntad, el Asegurador deberá notificarle su decisión de rescindir dentro del término de un mes y con un preaviso de siete días. Se aplicará el Artículo 39 de la Ley de Seguros si el riesgo no se hubiera asumido según las prácticas comerciales del Asegurador (Art. 40 - L. de S.).</p>            

            <p>
                La rescisión del contrato por agravación del riesgo da derecho al Asegurador:<br>
                a) Si la agravación del riesgo le fue comunicada oportunamente, a percibir la prima proporcional al tiempo transcurrido.<br>
                b) Si no le fue comunicada oportunamente, a percibir la prima por el período de seguro en curso (Art. 41 - L. de S.).
            </p>


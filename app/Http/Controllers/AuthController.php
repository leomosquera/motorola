    /**
     * Login user and create token
     *
     * @param  [string] email
     * @param  [string] password
     * @param  [boolean] remember_me
     * @return [string] access_token
     * @return [string] token_type
     * @return [string] expires_at
     */
    public function login(Request $request)
    {
        /** valido usuario */
        $user_validate = Validator::make($request->all(), ['username' => 'required|string']);
        $user_exists = Usuario::where('username', $request->username)->first() ?? false;
        if($user_validate->fails() || !$user_exists){
            return response()->json([
                'status' => 'error',
                'error' => 1,
                'message' => 'El username ingresado es incorrecto.'
            ], 401);
        }
        /** valido contraseña */
        $password_validate = Validator::make($request->all(), ['password' => 'required|string']);
        $credentials = request(['username', 'password']);
        if($password_validate->fails() || !Auth::attempt($credentials)){
            return response()->json([
                'status' => 'error',
                'error' => 2,
                'message' => 'La contraseña es incorrecta.'
            ], 401);
        }
        $user = $request->user();
        $tokenResult = $user->createToken('Personal Access Token');
        $token = $tokenResult->token;
        if ($request->remember_me)
            $token->expires_at = Carbon::now()->addWeeks(1);
        $token->save();
        return response()->json([
            'access_token' => $tokenResult->accessToken,
            'token_type' => 'Bearer',
            'expires_at' => Carbon::parse($tokenResult->token->expires_at)->toDateTimeString()
        ]);
    }

    /**
     * Logout user (Revoke the token)
     *
     * @return [string] message
     */
    public function logout(Request $request)
    {
        $request->user()->token()->revoke();
        return response()->json([
            'message' => 'Successfully logged out'
        ]);
    }

    /**
     * Get the authenticated User
     *
     * @return [json] user object
     */
    public function user(Request $request)
    {
      return response()->json($request->user());
    }
}

